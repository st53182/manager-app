/**
 * Единственный учебный блок на платформе: Модуль 1, три практики с полным ТЗ в заданиях.
 */
async function seedModuleOneCatalog(client) {
  const moduleCourse = {
    slug: 'ai-work-business-talk',
    title: 'Модуль 1. Лучшие ИИ-решения для работы и бизнеса',
    description:
      'Практический блок (~2,5 ч): как выбирать ИИ-инструменты под задачу и вести с ними диалог так, чтобы получать проверяемый результат. На платформе — три обязательные практики с письменным ответом и обратной связью ИИ.',
    sort_order: 1
  };

  await client.query(
    `INSERT INTO academy_courses (slug, title, description, sort_order)
     VALUES ($1, $2, $3, $4)
     ON CONFLICT (slug) DO UPDATE SET
       title = EXCLUDED.title,
       description = EXCLUDED.description,
       sort_order = EXCLUDED.sort_order`,
    [moduleCourse.slug, moduleCourse.title, moduleCourse.description, moduleCourse.sort_order]
  );

  const cr = await client.query(`SELECT id FROM academy_courses WHERE slug = $1`, [moduleCourse.slug]);
  const courseId = cr.rows[0]?.id;
  if (!courseId) return;

  const lessons = [
    {
      scenario_key: 'block1-practice-prompt',
      sort_order: 1,
      title: 'Практика 1. Промпт под рабочую задачу (RTCFSC)',
      content_md: `### Зачем эта практика
Научиться формулировать запрос к ИИ по схеме **RTCFSC** (роль, задача, контекст, формат, стиль, критерии) для реальной рабочей ситуации.

### Подсказка по структуре
- **R**ole — кто ассистент
- **T**ask — что сделать
- **C**ontext — фон, ограничения, аудитория
- **F**ormat — вид ответа (список, письмо, таблица…)
- **S**tyle — тон
- **C**riteria — как понять, что ответ хороший`,
      assignment_title: 'Практика 1: промпт RTCFSC для рабочей задачи',
      assignment_instructions: `## Контекст модуля
Вы проходите **Модуль 1** программы «Лучшие ИИ-решения для работы и бизнеса». Теория даётся на занятии со слайдами; на платформе — только **практика**: вы формулируете запрос, получаете результат и учитесь его проверять.

## Ситуация
Выберите **одну конкретную рабочую задачу** (свою или учебную):
- ответить клиенту на претензию или вопрос;
- подготовить короткую сводку совещания;
- набросать план действий по проекту;
- текст для внутренней рассылки / поста.

## Что нужно сделать
1. В поле **«Ваш ответ»** вставьте **готовый промпт** по RTCFSC (можно шестью подзаголовками R / T / C / F / S / C).
2. В промпте явно укажите: аудиторию результата; ограничения (объём, срок, что нельзя выдумывать); желаемый формат.
3. **Выполните промпт** в чате с наставником; в ответ добавьте **итог** (3–5 предложений): что получилось и что пришлось уточнять.
4. Укажите **одно слабое место** первого промпта и как улучшили бы формулировку (v2).

## Формат ответа (обязательно)
\`\`\`
Задача: …
Промпт (RTCFSC): …
Краткий результат: …
Слабое место промпта: …
Улучшение v2: …
\`\`\`

## Критерии проверки
- Промпт структурирован, без «напиши что-нибудь хорошее».
- Есть ограничения и критерии успеха.
- Есть ваша рефлексия, не только текст от ИИ.

## Режим
- **Индивидуально** — делаете сами.
- **Группа** — один вводит общий ответ; укажите размер группы и кто вводил.

## Не засчитывается
- Только вопрос наставнику без промпта.
- Промпт из одного предложения без контекста.`,
      rubric: {
        criteria: [
          'Структура RTCFSC',
          'Конкретика задачи и ограничений',
          'Итог выполнения и рефлексия',
          'Самооценка слабых мест'
        ],
        pass_hint: 'Промпт можно передать коллеге без устных пояснений.'
      }
    },
    {
      scenario_key: 'block1-practice-scenario',
      sort_order: 2,
      title: 'Практика 2. Диалог-сценарий с ИИ',
      content_md: `### Зачем эта практика
Отработать **диалог** с ИИ в роли второго участника (клиент, руководитель, сотрудник).

### Рекомендации
- Задайте роль и правила в первом сообщении.
- Сделайте 3–5 реплик, не один запрос.
- Зафиксируйте, где модель «срывается» из роли.`,
      assignment_title: 'Практика 2: ролевой сценарий с ИИ',
      assignment_instructions: `## Контекст
**Модуль 1**, практика 2. Цель — **спроектировать и провести** диалог с ИИ, а не получить готовый скрипт «под ключ».

## Выберите сценарий (один)
1. **Клиент** недоволен сроками — вы менеджер проекта.
2. **Руководитель** просит обосновать бюджет на внедрение ИИ-инструмента.
3. **Новый сотрудник** — обратная связь по первым двум неделям (1:1).
4. **Партнёр** сомневается в качестве продукта — короткий созвон.
(Можно свой сценарий — опишите в двух предложениях.)

## Что нужно сделать
В поле **«Ваш ответ»**:
1. Название сценария и **роли** (ИИ = …, вы = …).
2. **3–5 реплик** из реального чата с наставником («Я: …», «ИИ: …»).
3. Блок **«Выводы»** — минимум 4 пункта:
   - что сработало в постановке роли;
   - где модель ошиблась или дала общие фразы;
   - что уточнили во второй попытке;
   - как примените на работе (1 конкретный пример).

## Формат
\`\`\`
Сценарий: …
Роли: ИИ = …, я = …
Диалог: …
Выводы: • … • … • … • …
\`\`\`

## Критерии
- Роль задана чётко; диалог похож на переписку, а не монолог.
- Есть критика ответов модели.

## Группа
Один вводит сводный диалог; укажите, кто вёл чат.`,
      rubric: {
        criteria: [
          'Ясные роли и сценарий',
          'Фрагмент диалога (3+ реплики)',
          'Критический разбор ИИ',
          'Прикладные выводы'
        ],
        pass_hint: 'По тексту видно, что вы вели диалог, а не один раз запросили скрипт.'
      }
    },
    {
      scenario_key: 'block1-practice-hallucination',
      sort_order: 3,
      title: 'Практика 3. Проверка ответа ИИ на ошибки',
      content_md: `### Зачем эта практика
ИИ может уверенно писать **неверные факты**, цифры и ссылки. Нужен навык **проверки** перед отправкой в работу.

### Алгоритм
1. Выделить утверждения, требующие источника.
2. Пометить тип риска.
3. Переписать безопасную формулировку.`,
      assignment_title: 'Практика 3: разбор опасного ответа ИИ',
      assignment_instructions: `## Контекст
**Модуль 1**, практика 3. Учимся **замечать галлюцинации и слабые места** до отправки текста коллеге или клиенту.

## Исходный фрагмент (выберите один вариант)
**А)** Скопируйте 1–2 абзаца из **вашего чата** (практики 1–2), где есть цифры, «факты» или ссылки.

**Б)** Или разберите учебный фрагмент:
> «По данным исследования McKinsey 2024, 87% компаний в СНГ уже внедрили GPT-4 в CRM. Рекомендуем немедленно подписать годовой контракт на корпоративный Copilot — ROI 340% за 6 недель. Источник: Forbes, март 2025.»

## Что нужно сделать
1. **Список из минимум 4 утверждений**, которые нельзя принимать без проверки.
2. Для каждого — **тип проблемы**: выдуманный факт / неверная цифра / fake citation / overconfidence / слишком общее.
3. **Безопасная переформулировка** всего фрагмента (5–7 предложений) для рабочей переписки.
4. **Ваш чек-лист из 5 пунктов**: как вы проверяете ответы ИИ перед отправкой.

## Формат
\`\`\`
Исходный фрагмент: …
Проблемы: 1) … 2) …
Безопасная версия: …
Мой чек-лист: • …
\`\`\`

## Завершение модуля
Отправьте ответ → **«Обратная связь ИИ»** → при необходимости доработайте → **«Отметить пройденным»**. В прогрессе должно быть **3/3** практики.`,
      rubric: {
        criteria: [
          'Спорные утверждения выделены',
          'Типы рисков названы',
          'Безопасная переформулировка',
          'Личный чек-лист проверки'
        ],
        pass_hint: 'Понятно, что было не так и как проверять в следующий раз.'
      }
    }
  ];

  for (const L of lessons) {
    const ins = await client.query(
      `INSERT INTO academy_lessons (course_id, title, content_md, scenario_key, sort_order)
       VALUES ($1, $2, $3, $4, $5)
       ON CONFLICT (course_id, scenario_key) DO UPDATE SET
         title = EXCLUDED.title,
         content_md = EXCLUDED.content_md,
         sort_order = EXCLUDED.sort_order
       RETURNING id`,
      [courseId, L.title, L.content_md, L.scenario_key, L.sort_order]
    );
    const lessonId = ins.rows[0]?.id;
    if (!lessonId) continue;
    await client.query(
      `INSERT INTO academy_assignments (lesson_id, title, instructions_md, rubric_json)
       VALUES ($1, $2, $3, $4::jsonb)
       ON CONFLICT (lesson_id) DO UPDATE SET
         title = EXCLUDED.title,
         instructions_md = EXCLUDED.instructions_md,
         rubric_json = EXCLUDED.rubric_json`,
      [lessonId, L.assignment_title, L.assignment_instructions, JSON.stringify(L.rubric)]
    );
  }
}

module.exports = { seedModuleOneCatalog };
